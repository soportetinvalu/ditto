final class Preferences {
    let defaults: UserDefaults
    init(_ defaults: UserDefaults = .standard) {
        self.defaults = defaults
        defaults.register(defaults: ["captureEnabled": false, "paused": false, "pollMilliseconds": 350,
                                    "excluded": "com.apple.keychainaccess", "allowed": "",
                                    "days": 30, "maxCount": 5000, "megabytes": 512,
                                    "separator": "\n", "reorder": true, "autoPaste": false,
                                    "hotKey": 50, "hotModifiers": Int(controlKey | optionKey),
                                    "appearance": "system", "customTypes": false])
    }
    var shortcut: ShortcutConfiguration { ShortcutConfiguration.load(from: defaults) }
    var enabled: Bool { defaults.bool(forKey: "captureEnabled") }
    var paused: Bool { get { defaults.bool(forKey: "paused") } set { defaults.set(newValue, forKey: "paused") } }
    var excluded: String { defaults.string(forKey: "excluded") ?? "" }
    var allowed: String { defaults.string(forKey: "allowed") ?? "" }
    var separator: String { defaults.string(forKey: "separator") ?? "\n" }
    func allowed(source: String, transient: Bool) -> Bool {
        cm_capture_allowed(paused ? 1 : 0, source, excluded, allowed, transient ? 1 : 0) != 0
    }
    func applyAppearance() {
        let choice = defaults.string(forKey: "appearance")
        NSApp.appearance = choice == "light" ? NSAppearance(named: .aqua) : choice == "dark" ? NSAppearance(named: .darkAqua) : nil
    }
}

final class ClipboardMonitor {
    let store: ClipStore
    let preferences: Preferences
    let pasteboard: NSPasteboard
    var onChange: (() -> Void)?
    var onMessage: ((String) -> Void)?
    private var timer: Timer?
    private var lastCount: Int?
    private var ownCount: Int?
    static let sensitiveTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    static let supported: Set<String> = [NSPasteboard.PasteboardType.string.rawValue,
                                         NSPasteboard.PasteboardType.rtf.rawValue, NSPasteboard.PasteboardType.rtfd.rawValue,
                                         NSPasteboard.PasteboardType.html.rawValue, NSPasteboard.PasteboardType.png.rawValue,
                                         NSPasteboard.PasteboardType.tiff.rawValue, NSPasteboard.PasteboardType.fileURL.rawValue,
                                         NSPasteboard.PasteboardType.URL.rawValue, "public.utf16-external-plain-text", "public.jpeg"]
    init(store: ClipStore, preferences: Preferences, pasteboard: NSPasteboard) {
        self.store = store; self.preferences = preferences; self.pasteboard = pasteboard
    }
    func start() {
        timer?.invalidate(); timer = nil
        guard preferences.enabled else { return }
        // Do not ingest pre-existing clipboard data when consent is first given.
        lastCount = pasteboard.changeCount
        let interval = Double(max(150, min(2000, preferences.defaults.integer(forKey: "pollMilliseconds")))) / 1000
        timer = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { [weak self] _ in self?.poll() }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }
    func stop() { timer?.invalidate(); timer = nil }
    func markOwnWrite() { ownCount = pasteboard.changeCount; lastCount = ownCount }
    func poll(source: String? = nil) {
        guard preferences.enabled else { return }
        let count = pasteboard.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard count != ownCount else { return }
        guard !preferences.paused else { return } // no materialization while paused
        let app = source ?? NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? ""
        guard app != Bundle.main.bundleIdentifier else { return }
        guard preferences.allowed(source: app, transient: false) else { return }
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return }
        let concealed = items.contains { item in !Set(item.types.map(\.rawValue)).isDisjoint(with: Self.sensitiveTypes) }
        guard preferences.allowed(source: app, transient: concealed) else { return }
        var reps = [Representation](); var total = 0
        for (index, item) in items.enumerated() {
            for type in item.types {
                guard Self.supported.contains(type.rawValue) || preferences.defaults.bool(forKey: "customTypes") else { continue }
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                guard total <= Int(CM_MAX_BYTES), reps.count < Int(CM_MAX_REPRESENTATIONS) else {
                    onMessage?("Copia omitida: supera el límite de 32 MiB/256 formatos."); return
                }
                reps.append(Representation(item: index, type: type.rawValue, data: data))
            }
        }
        guard pasteboard.changeCount == count, !reps.isEmpty else { return }
        let plain = Self.plainText(reps)
        let title = plain.isEmpty ? (reps.contains { $0.type == NSPasteboard.PasteboardType.png.rawValue || $0.type == NSPasteboard.PasteboardType.tiff.rawValue } ? "Imagen" : "Copia multiformato") : String(plain.replacingOccurrences(of: "\n", with: " ⏎ ").prefix(120))
        do {
            try store.capture(reps, title: title, text: plain, source: app)
            try store.retain(days: preferences.defaults.integer(forKey: "days"), count: preferences.defaults.integer(forKey: "maxCount"), megabytes: preferences.defaults.integer(forKey: "megabytes"))
            onChange?()
        } catch { onMessage?(error.localizedDescription) }
    }
    static func plainText(_ reps: [Representation]) -> String {
        let indices = Set(reps.map(\.item)).sorted()
        return indices.compactMap { index -> String? in
            let item = reps.filter { $0.item == index }
            if let data = item.first(where: { $0.type == NSPasteboard.PasteboardType.string.rawValue })?.data,
               let text = String(data: data, encoding: .utf8) { return text }
            if let data = item.first(where: { $0.type == "public.utf16-external-plain-text" })?.data,
               let text = String(data: data, encoding: .utf16) { return text }
            if let data = item.first(where: { $0.type == NSPasteboard.PasteboardType.rtf.rawValue })?.data,
               let text = try? NSAttributedString(data: data, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil) { return text.string }
            // HTML is never loaded as a document. Removing tags is intentionally not a general HTML renderer.
            if let data = item.first(where: { $0.type == NSPasteboard.PasteboardType.html.rawValue })?.data,
               let html = String(data: data, encoding: .utf8) {
                return html.replacingOccurrences(of: "(?is)<(script|style)\\b[^>]*>.*?</\\1>", with: "", options: .regularExpression)
                    .replacingOccurrences(of: "(?s)<[^>]*>", with: "", options: .regularExpression)
                    .replacingOccurrences(of: "&lt;", with: "<").replacingOccurrences(of: "&gt;", with: ">")
                    .replacingOccurrences(of: "&nbsp;", with: " ").replacingOccurrences(of: "&amp;", with: "&")
            }
            if let url = item.first(where: { $0.type == NSPasteboard.PasteboardType.fileURL.rawValue || $0.type == NSPasteboard.PasteboardType.URL.rawValue }), let text = String(data: url.data, encoding: .utf8) { return text }
            return nil
        }.joined(separator: "\n")
    }
    @discardableResult
    func write(_ reps: [Representation]) throws -> Int {
        try ClipStore.validate(reps)
        var items = [NSPasteboardItem]()
        for index in Set(reps.map(\.item)).sorted() {
            let item = NSPasteboardItem()
            for rep in reps where rep.item == index {
                guard item.setData(rep.data, forType: NSPasteboard.PasteboardType(rep.type)) else { throw LocalError("No se pudo preparar un formato del portapapeles.") }
            }
            items.append(item)
        }
        pasteboard.clearContents()
        guard pasteboard.writeObjects(items) else { markOwnWrite(); throw LocalError("No se pudo escribir el portapapeles. No se envió ningún pegado.") }
        markOwnWrite(); return pasteboard.changeCount
    }
}

final class PasteCoordinator {
    let monitor: ClipboardMonitor
    let preferences: Preferences
    var destination: NSRunningApplication?
    var onMessage: ((String) -> Void)?
    init(monitor: ClipboardMonitor, preferences: Preferences) { self.monitor = monitor; self.preferences = preferences }
    func rememberDestination() {
        let app = NSWorkspace.shared.frontmostApplication
        if app?.processIdentifier != ProcessInfo.processInfo.processIdentifier { destination = app }
    }
    func paste(_ reps: [Representation], hide: () -> Void) throws {
        let count = try monitor.write(reps)
        guard preferences.defaults.bool(forKey: "autoPaste") else {
            hide(); _ = destination?.activate(options: [.activateIgnoringOtherApps])
            onMessage?("Copiado. Pulsa ⌘V en la aplicación de destino."); return
        }
        guard AXIsProcessTrusted() else {
            // Only explicit user action requests the OS prompt, never startup or polling.
            let alert = NSAlert()
            alert.messageText = "Permitir el pegado automático"
            alert.informativeText = "Accesibilidad permite enviar una sola pulsación ⌘V a la aplicación anterior. La copia ya está disponible para pegar manualmente. Puedes revocar este acceso en Ajustes del Sistema."
            alert.addButton(withTitle: "Solicitar permiso"); alert.addButton(withTitle: "Solo copiar")
            if alert.runModal() == .alertFirstButtonReturn {
                _ = AXIsProcessTrustedWithOptions([kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary)
            }
            // Do not queue a paste waiting for permission; it may land in an unrelated app.
            onMessage?("Copiado. El permiso no provoca un pegado pendiente: usa ⌘V o vuelve a seleccionar.")
            return
        }
        guard let app = destination, !app.isTerminated, app.processIdentifier != ProcessInfo.processInfo.processIdentifier else {
            onMessage?("Copiado. No hay una aplicación anterior válida; pega manualmente con ⌘V."); return
        }
        hide()
        guard app.activate(options: [.activateIgnoringOtherApps]) else { onMessage?("Copiado. No se pudo activar el destino."); return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.20) { [weak self] in
            guard let self else { return }
            guard self.monitor.pasteboard.changeCount == count, AXIsProcessTrusted(),
                  NSWorkspace.shared.frontmostApplication?.processIdentifier == app.processIdentifier,
                  !app.isTerminated else {
                self.onMessage?("Copiado; pegado automático cancelado porque cambió el destino o el portapapeles."); return
            }
            guard let down = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: true),
                  let up = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: false) else {
                self.onMessage?("Copiado; no se pudo crear ⌘V. Pega manualmente."); return
            }
            down.flags = .maskCommand; up.flags = .maskCommand
            down.post(tap: .cghidEventTap); up.post(tap: .cghidEventTap)
            self.onMessage?("Se envió ⌘V. Si el destino lo rechaza, pega manualmente; no se reintenta.")
        }
    }
}

final class GlobalShortcut {
    private var handler: EventHandlerRef?
    private var handlerStatus: OSStatus = noErr
    private lazy var registration = ShortcutRegistration<EventHotKeyRef>(acquire: { candidate in
        var reference: EventHotKeyRef?
        let id = EventHotKeyID(signature: OSType(0x4d454d4c), id: 1)
        let rc = RegisterEventHotKey(candidate.keyCode, candidate.modifiers, id, GetApplicationEventTarget(), 0, &reference)
        guard rc == noErr, let reference else {
            throw LocalError("El atajo global no está disponible (\(rc)). Puede estar reservado por macOS u otra app. Se conserva el atajo anterior; elige otra combinación.")
        }
        return reference
    }, release: { UnregisterEventHotKey($0) })
    var action: (() -> Void)?
    init() {
        var event = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        handlerStatus = InstallEventHandler(GetApplicationEventTarget(), { _, _, context in
            guard let context else { return OSStatus(eventNotHandledErr) }
            Unmanaged<GlobalShortcut>.fromOpaque(context).takeUnretainedValue().action?()
            return noErr
        }, 1, &event, Unmanaged.passUnretained(self).toOpaque(), &handler)
    }
    func register(_ configuration: ShortcutConfiguration) throws {
        guard handlerStatus == noErr else {
            throw LocalError("No se pudo instalar el manejador del atajo (\(handlerStatus)). Usa el icono de menú.")
        }
        try registration.replace(with: configuration)
    }
    deinit { if let handler { RemoveEventHandler(handler) } }
}

enum TextTransform: String, CaseIterable {
    case trim = "Recortar espacios", upper = "MAYÚSCULAS", lower = "minúsculas", title = "Tipo Título", camel = "camelCase"
    func apply(_ input: String) -> String {
        switch self {
        case .trim: return input.trimmingCharacters(in: .whitespacesAndNewlines)
        case .upper: return input.uppercased()
        case .lower: return input.lowercased()
        case .title: return input.capitalized
        case .camel:
            let words = input.components(separatedBy: CharacterSet.alphanumerics.inverted).filter { !$0.isEmpty }
            return (words.first?.lowercased() ?? "") + words.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst().lowercased() }.joined()
        }
    }
}

enum Preview {
    static func image(_ data: Data) -> NSImage? {
        guard data.count <= Int(CM_MAX_BYTES), let source = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let w = props[kCGImagePropertyPixelWidth] as? Int, let h = props[kCGImagePropertyPixelHeight] as? Int,
              w > 0, h > 0, w <= 16000, h <= 16000, w * h <= 40_000_000 else { return nil }
        return NSImage(data: data)
    }
    static func qr(_ text: String) -> NSImage? {
        guard text.utf8.count <= 2000, let filter = CIFilter(name: "CIQRCodeGenerator") else { return nil }
        filter.setValue(Data(text.utf8), forKey: "inputMessage")
        guard let result = filter.outputImage?.transformed(by: CGAffineTransform(scaleX: 6, y: 6)),
              let cg = CIContext().createCGImage(result, from: result.extent) else { return nil }
        return NSImage(cgImage: cg, size: .zero)
    }
}
